from decimal import Decimal
from types import SimpleNamespace

from app.llm_provider import LlmProviderResult
from app.llm_sop_generator import LlmSopGenerator
from app.sop_schema import SopPayload, SopStep


class FakeDb:
    def __init__(self):
        self.added = []

    def add(self, item):
        self.added.append(item)


class SuccessfulProvider:
    name = "openai"
    model = "gpt-4o"

    def __init__(self):
        self.session_payload = None

    def generate_sop(self, session_payload: dict) -> LlmProviderResult:
        self.session_payload = session_payload
        return LlmProviderResult(
            sop=SopPayload(
                title=f"LLM Draft: {session_payload['workflow_name']}",
                summary="Generated by test provider.",
                steps=[
                    SopStep(
                        order=1,
                        title="Use workflow events",
                        instruction="Generate SOP from the ordered event log.",
                        branch="main",
                        source_event_ids=[
                            event["id"] for event in session_payload.get("events", [])
                        ],
                    )
                ],
            ),
            prompt_tokens=10,
            completion_tokens=20,
            cost_usd=Decimal("0.001"),
        )


def test_llm_sop_generator_returns_llm_payload(monkeypatch):
    provider = SuccessfulProvider()
    monkeypatch.setattr(
        "app.llm_sop_generator.get_llm_provider",
        lambda: provider,
    )

    session = SimpleNamespace(
        id="aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa",
        workflow_name="Login Flow",
        events=[
            SimpleNamespace(
                id=1,
                seq=0,
                type="navigation",
                target_label="Sign in",
                target_selector="button[type='submit']",
                value="[MASKED]",
                url="https://example.com/login",
                attrs={"page_title": "Login"},
                timestamp_ms=1000,
            )
        ],
    )

    db = FakeDb()
    generator = LlmSopGenerator(db=db)
    payload = generator.generate(session)
    event_payload = provider.session_payload["events"][0]

    assert payload.title == "LLM Draft: Login Flow"
    assert payload.steps[0].source_event_ids == ["1"]
    assert generator.generation_mode == "llm"
    assert payload.generation_mode == "llm"
    assert len(db.added) == 1
    assert db.added[0].status == "success"
    assert db.added[0].provider == "openai"
    assert db.added[0].model == "gpt-4o"
    assert db.added[0].attempt == 1
    assert db.added[0].latency_ms >= 0
    assert db.added[0].prompt_tokens == 10
    assert db.added[0].completion_tokens == 20
    assert db.added[0].cost_usd == Decimal("0.001")
    assert payload.steps[0].branch == "main"

    assert event_payload["target_label"] == "Sign in"
    assert event_payload["value"] == "[MASKED]"
    assert event_payload["attrs"] == {"page_title": "Login"}
    assert event_payload["page_title"] == "Login"
    assert event_payload["timestamp_ms"] == 1000


class FailingProvider:
    name = "openai"
    model = "gpt-4o"

    def generate_sop(self, session_payload: dict) -> LlmProviderResult:
        raise RuntimeError("provider failed")


def test_llm_sop_generator_falls_back_after_failures(monkeypatch):
    monkeypatch.setattr(
        "app.llm_sop_generator.get_llm_provider",
        lambda: FailingProvider(),
    )
    monkeypatch.setattr("app.llm_sop_generator.time.sleep", lambda seconds: None)

    session = SimpleNamespace(
        id="aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa",
        workflow_name="Login Flow",
        events=[
            SimpleNamespace(
                id=1,
                seq=0,
                type="navigation",
                target_label=None,
                target_selector=None,
                url="https://example.com/login",
            )
        ],
    )

    db = FakeDb()
    generator = LlmSopGenerator(db=db)
    payload = generator.generate(session)

    assert payload.title == "Login Flow"
    assert generator.generation_mode == "fallback"
    assert payload.generation_mode == "fallback"
    assert [entry.status for entry in db.added] == [
        "error",
        "error",
        "error",
        "error",
    ]
    assert [entry.attempt for entry in db.added] == [1, 2, 3, 4]
    assert all(entry.error_message == "provider failed" for entry in db.added)


def test_llm_sop_generator_uses_exponential_backoff(monkeypatch):
    sleeps = []

    provider = FailingProvider()
    monkeypatch.setattr(
        "app.llm_sop_generator.get_llm_provider",
        lambda: provider,
    )
    monkeypatch.setattr(
        "app.llm_sop_generator.time.sleep",
        lambda seconds: sleeps.append(seconds),
    )

    session = SimpleNamespace(
        id="aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa",
        workflow_name="Login Flow",
        events=[
            SimpleNamespace(
                id=1,
                seq=0,
                type="navigation",
                target_label=None,
                target_selector=None,
                url="https://example.com/login",
            )
        ],
    )

    generator = LlmSopGenerator(max_retries=3)
    generator.generate(session)

    assert sleeps == [1, 2, 4]
    assert generator.generation_mode == "fallback"
